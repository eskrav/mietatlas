-- Database schema, part 2: storage for a policy impact model ("proposal X -> effect Y").
-- Model inputs (parameters, scenarios), model runs and their results, kept traceable:
-- every published number can be traced to the run, model version, data release and
-- exact parameter values that produced it. Requires db/schema.sql (regions, indicators,
-- sources), so run it after load_db.py:
--   psql -d mietatlas -f db/model_schema.sql
-- Safe to run repeatedly.

-- ---------------------------------------------------------------------------
-- Model inputs
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS atlas.household_types (
    household_type_id text PRIMARY KEY,         -- model household, e.g. 'single'
    label             text NOT NULL
);

-- Every model input with its baseline value. kind separates what policy can change
-- (lever) from fixed definitions, estimated relationships and assumptions.
CREATE TABLE IF NOT EXISTS atlas.parameters (
    parameter_id   text PRIMARY KEY,            -- e.g. 'kappungsgrenze'
    name           text    NOT NULL,
    unit           text    NOT NULL,
    baseline_value numeric NOT NULL,
    kind           text    NOT NULL
                   CHECK (kind IN ('lever', 'definitional', 'empirical', 'assumption')),
    source_id      text REFERENCES atlas.sources (source_id),  -- NULL for assumptions
    valid_min      numeric,                     -- range the model is validated for
    valid_max      numeric,
    CHECK (valid_min IS NULL OR valid_max IS NULL OR valid_min <= valid_max),
    CHECK (valid_min IS NULL OR baseline_value >= valid_min),
    CHECK (valid_max IS NULL OR baseline_value <= valid_max)
);

CREATE TABLE IF NOT EXISTS atlas.scenarios (
    scenario_id  text PRIMARY KEY,
    name         text    NOT NULL,
    description  text,
    is_baseline  boolean NOT NULL DEFAULT false,
    is_published boolean NOT NULL DEFAULT false
);

-- At most one baseline scenario
CREATE UNIQUE INDEX IF NOT EXISTS scenarios_one_baseline
    ON atlas.scenarios (is_baseline) WHERE is_baseline;

-- A scenario stores only the parameter values it changes;
-- every other parameter keeps its baseline value.
CREATE TABLE IF NOT EXISTS atlas.scenario_overrides (
    scenario_id  text    NOT NULL REFERENCES atlas.scenarios (scenario_id) ON DELETE CASCADE,
    parameter_id text    NOT NULL REFERENCES atlas.parameters (parameter_id),
    value        numeric NOT NULL,
    PRIMARY KEY (scenario_id, parameter_id)
);

-- Full parameter set per scenario: the override if there is one, otherwise the baseline
CREATE OR REPLACE VIEW atlas.effective_parameters AS
SELECT s.scenario_id,
       p.parameter_id,
       p.unit,
       COALESCE(o.value, p.baseline_value) AS value,
       (o.value IS NOT NULL)               AS is_override
FROM atlas.scenarios s
CROSS JOIN atlas.parameters p
LEFT JOIN atlas.scenario_overrides o
       ON o.scenario_id = s.scenario_id
      AND o.parameter_id = p.parameter_id;

-- ---------------------------------------------------------------------------
-- Model runs and results
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS atlas.model_runs (
    run_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario_id   text NOT NULL REFERENCES atlas.scenarios (scenario_id),
    model_version text NOT NULL,                -- e.g. git tag of the model code
    data_release  text NOT NULL,                -- which data release the run used
    run_at        timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS model_runs_scenario_idx
    ON atlas.model_runs (scenario_id, run_at DESC);

-- Copy of the exact parameter values a run used, written at run time, so a published
-- number stays traceable even if a baseline value or a scenario is edited later
CREATE TABLE IF NOT EXISTS atlas.run_parameters (
    run_id       integer NOT NULL REFERENCES atlas.model_runs (run_id) ON DELETE CASCADE,
    parameter_id text    NOT NULL REFERENCES atlas.parameters (parameter_id),
    value        numeric NOT NULL,
    PRIMARY KEY (run_id, parameter_id)
);

CREATE TABLE IF NOT EXISTS atlas.results (
    run_id            integer NOT NULL REFERENCES atlas.model_runs (run_id) ON DELETE CASCADE,
    region_id         text    NOT NULL REFERENCES atlas.regions (region_id),
    household_type_id text    NOT NULL REFERENCES atlas.household_types (household_type_id),
    indicator_id      text    NOT NULL REFERENCES atlas.indicators (indicator_id),
    year              integer NOT NULL CHECK (year BETWEEN 1990 AND 2100),
    value             numeric NOT NULL,
    PRIMARY KEY (run_id, region_id, household_type_id, indicator_id, year)
);

-- What an interface would read: the latest run of each published scenario,
-- without internal run IDs
CREATE OR REPLACE VIEW atlas.published_results AS
WITH latest_runs AS (
    SELECT DISTINCT ON (r.scenario_id)
           r.run_id, r.scenario_id
    FROM atlas.model_runs r
    JOIN atlas.scenarios s USING (scenario_id)
    WHERE s.is_published
    ORDER BY r.scenario_id, r.run_at DESC, r.run_id DESC  -- run_id breaks ties
)
SELECT lr.scenario_id,
       res.region_id,
       res.household_type_id,
       res.indicator_id,
       res.year,
       res.value
FROM latest_runs lr
JOIN atlas.results res USING (run_id);
